import { Document, Font, Image, Page, StyleSheet, Text, View } from "@react-pdf/renderer";
import { PERSON_STATUS_LABEL } from "@/lib/reports/compute";
import { PDF_COLORS as C } from "@/lib/reports/pdf-theme";
import type { PersonStatus, ReportView } from "@/lib/reports/types";

// react-pdf hyphenates by default ("Guid-ance"). Names and departments must stay whole.
Font.registerHyphenationCallback((word) => [word]);

export interface ReportDocumentProps {
  term: string;
  view: ReportView;
  generatedAt: Date;
  generatedBy?: string;
  /** PNG/JPG data URL. Omit to render without a logo. */
  logo?: string;
}

const s = StyleSheet.create({
  page: { paddingTop: 36, paddingHorizontal: 36, paddingBottom: 56, fontSize: 9, fontFamily: "Helvetica", color: C.text },
  brandBar: { height: 4, backgroundColor: C.amber, marginBottom: 14 },
  brandRow: { flexDirection: "row", alignItems: "center" },
  logo: { width: 30, height: 30, marginRight: 9, objectFit: "contain" },
  org: { fontSize: 11, fontFamily: "Helvetica-Bold" },
  orgSub: { fontSize: 8, color: C.muted, marginTop: 1 },
  title: { fontSize: 22, fontFamily: "Helvetica-Bold", marginTop: 14 },
  metaRow: { flexDirection: "row", marginTop: 12 },
  metaItem: { marginRight: 28 },
  metaLabel: { fontSize: 8, color: C.muted },
  metaValue: { fontSize: 10, marginTop: 1 },

  kpiRow: { flexDirection: "row", marginTop: 18 },
  kpi: { flex: 1, borderWidth: 1, borderColor: C.border, borderRadius: 4, padding: 10, marginRight: 8 },
  kpiLast: { marginRight: 0 },
  kpiValue: { fontSize: 20, fontFamily: "Helvetica-Bold" },
  kpiLabel: { fontSize: 8, color: C.muted, marginTop: 2 },

  sectionTitle: { fontSize: 13, fontFamily: "Helvetica-Bold", marginTop: 22, marginBottom: 4 },
  sectionNote: { fontSize: 8, color: C.muted, marginBottom: 8 },

  th: { flexDirection: "row", backgroundColor: C.surface, borderTopWidth: 1, borderBottomWidth: 1, borderColor: C.border, paddingVertical: 5, paddingHorizontal: 6 },
  thText: { fontFamily: "Helvetica-Bold", fontSize: 8, color: C.muted },
  tr: { flexDirection: "row", alignItems: "center", borderBottomWidth: 1, borderColor: C.border, paddingVertical: 5, paddingHorizontal: 6 },
  trAlt: { backgroundColor: C.zebra },
  num: { textAlign: "right" },

  track: { flexDirection: "row", height: 6, borderRadius: 3, backgroundColor: C.track, overflow: "hidden" },
  barWrap: { flexDirection: "row", alignItems: "center" },
  barPct: { width: 30, textAlign: "right", fontSize: 8, marginLeft: 6 },

  footer: { position: "absolute", left: 36, right: 36, bottom: 22, flexDirection: "row", justifyContent: "space-between", fontSize: 8, color: C.muted },
});

/* Column widths (content width on A4 with 36pt margins is ~523pt). */
const TEMPLATE_COLS = { name: "30%", n: "10%", bar: "30%" }; // name + 4 numeric (n) + bar = 100%
const DEPT_COLS = { name: "24%", n: "11.5%", bar: "41.5%" }; // name + 3 numeric (n) + bar = 100%
const LIST_COLS = { name: "26%", id: "15%", tpl: "11%", status: "14%", out: "34%" };

const STATUS_TEXT_COLOR: Record<PersonStatus, string> = {
  cleared: C.approved,
  pending: C.pendingText,
  incomplete: C.incompleteText,
};

function formatDate(date: Date) {
  return new Intl.DateTimeFormat("en-PH", { dateStyle: "long", timeStyle: "short" }).format(date);
}

export function ReportDocument({ term, view, generatedAt, generatedBy, logo }: ReportDocumentProps) {
  const { totals, templates, departments, rows } = view;

  return (
    <Document title={`Clearance Report - ${term}`} author={generatedBy ?? "STI WebC"} subject={view.scopeLabel}>
      <Page size="A4" style={s.page}>
        {/* Header */}
        <View style={s.brandBar} />
        <View style={s.brandRow}>
          {logo ? <Image src={logo} style={s.logo} /> : null}
          <View>
            <Text style={s.org}>STI WebC</Text>
            <Text style={s.orgSub}>Clearance Portal</Text>
          </View>
        </View>
        <Text style={s.title}>Clearance Report</Text>

        <View style={s.metaRow}>
          <Meta label="Term" value={term} />
          <Meta label="Scope" value={view.scopeLabel} />
          <Meta label="Generated" value={formatDate(generatedAt)} />
          {generatedBy ? <Meta label="Generated by" value={generatedBy} /> : null}
        </View>

        {/* KPIs */}
        <View style={s.kpiRow}>
          <Kpi value={String(totals.total)} label="Total in scope" />
          <Kpi value={String(totals.cleared)} label={`Fully cleared (${totals.rate}%)`} />
          <Kpi value={String(totals.incomplete)} label="Incomplete tasks" />
          <Kpi value={String(totals.pending)} label="Pending review" last />
        </View>

        {/* Completion by template */}
        <Text style={s.sectionTitle}>Completion by template</Text>
        <View style={s.th}>
          <Text style={[s.thText, { width: TEMPLATE_COLS.name }]}>Template</Text>
          <Text style={[s.thText, s.num, { width: TEMPLATE_COLS.n }]}>Total</Text>
          <Text style={[s.thText, s.num, { width: TEMPLATE_COLS.n }]}>Cleared</Text>
          <Text style={[s.thText, s.num, { width: TEMPLATE_COLS.n }]}>Incomplete</Text>
          <Text style={[s.thText, s.num, { width: TEMPLATE_COLS.n }]}>Review</Text>
          <Text style={[s.thText, { width: TEMPLATE_COLS.bar, paddingLeft: 12 }]}>Completion</Text>
        </View>
        {templates.map((t, i) => (
          <View key={t.code} style={[s.tr, i % 2 ? s.trAlt : {}]} wrap={false}>
            <View style={{ width: TEMPLATE_COLS.name, paddingRight: 6 }}>
              <Text style={{ fontFamily: "Helvetica-Bold" }}>{t.kind === "staff" ? "Staff" : t.code}</Text>
              <Text style={{ fontSize: 7.5, color: C.muted }}>{t.name}</Text>
            </View>
            <Text style={[s.num, { width: TEMPLATE_COLS.n }]}>{t.total}</Text>
            <Text style={[s.num, { width: TEMPLATE_COLS.n }]}>{t.cleared}</Text>
            <Text style={[s.num, { width: TEMPLATE_COLS.n }]}>{t.incomplete}</Text>
            <Text style={[s.num, { width: TEMPLATE_COLS.n }]}>{t.pending}</Text>
            <View style={[s.barWrap, { width: TEMPLATE_COLS.bar, paddingLeft: 12 }]}>
              <View style={[s.track, { flex: 1 }]}>
                <View style={{ width: `${t.rate}%`, backgroundColor: C.navy }} />
              </View>
              <Text style={s.barPct}>{t.rate}%</Text>
            </View>
          </View>
        ))}

        {/* Department sign-offs */}
        <Text style={s.sectionTitle}>Department sign-offs</Text>
        <Text style={s.sectionNote}>Each requirement counts once per person, per department.</Text>
        <View style={s.th}>
          <Text style={[s.thText, { width: DEPT_COLS.name }]}>Department</Text>
          <Text style={[s.thText, s.num, { width: DEPT_COLS.n }]}>Approved</Text>
          <Text style={[s.thText, s.num, { width: DEPT_COLS.n }]}>Review</Text>
          <Text style={[s.thText, s.num, { width: DEPT_COLS.n }]}>Incomplete</Text>
          <Text style={[s.thText, { width: DEPT_COLS.bar, paddingLeft: 12 }]}>Distribution</Text>
        </View>
        {departments.map((d, i) => (
          <View key={d.department} style={[s.tr, i % 2 ? s.trAlt : {}]} wrap={false}>
            <Text style={{ width: DEPT_COLS.name }}>{d.department}</Text>
            <Text style={[s.num, { width: DEPT_COLS.n }]}>{d.approved}</Text>
            <Text style={[s.num, { width: DEPT_COLS.n }]}>{d.pending}</Text>
            <Text style={[s.num, { width: DEPT_COLS.n }]}>{d.incomplete}</Text>
            <View style={{ width: DEPT_COLS.bar, paddingLeft: 12 }}>
              <View style={s.track}>
                <View style={{ flexGrow: d.approved, flexBasis: 0, backgroundColor: C.approved }} />
                <View style={{ flexGrow: d.pending, flexBasis: 0, backgroundColor: C.pending }} />
                <View style={{ flexGrow: d.incomplete, flexBasis: 0, backgroundColor: C.incomplete }} />
              </View>
            </View>
          </View>
        ))}
        <View style={{ flexDirection: "row", marginTop: 8 }}>
          <LegendDot color={C.approved} label="Approved" />
          <LegendDot color={C.pending} label="Pending review" />
          <LegendDot color={C.incomplete} label="Incomplete" />
        </View>

        {/* Status list starts on its own page so the repeated header behaves predictably */}
        <View break>
          <Text style={[s.sectionTitle, { marginTop: 0 }]}>Clearance status list</Text>
          <Text style={s.sectionNote}>
            {rows.length} {rows.length === 1 ? "record" : "records"} in scope, grouped by template and sorted by name.
          </Text>

          <View style={s.th} fixed>
            <Text style={[s.thText, { width: LIST_COLS.name }]}>Name</Text>
            <Text style={[s.thText, { width: LIST_COLS.id }]}>ID number</Text>
            <Text style={[s.thText, { width: LIST_COLS.tpl }]}>Template</Text>
            <Text style={[s.thText, { width: LIST_COLS.status }]}>Status</Text>
            <Text style={[s.thText, { width: LIST_COLS.out }]}>Outstanding sign-offs</Text>
          </View>

          {rows.map((r, i) => (
            <View key={r.id} style={[s.tr, { alignItems: "flex-start" }, i % 2 ? s.trAlt : {}]} wrap={false}>
              <Text style={{ width: LIST_COLS.name, paddingRight: 6 }}>{r.name}</Text>
              <Text style={{ width: LIST_COLS.id }}>{r.idNumber}</Text>
              <Text style={{ width: LIST_COLS.tpl }}>{r.templateCode === "STAFF" ? "Staff" : r.templateCode}</Text>
              <Text style={{ width: LIST_COLS.status, fontFamily: "Helvetica-Bold", color: STATUS_TEXT_COLOR[r.status] }}>
                {PERSON_STATUS_LABEL[r.status]}
              </Text>
              <Text style={{ width: LIST_COLS.out, color: r.outstanding.length ? C.text : C.muted }}>
                {r.outstanding.length
                  ? r.outstanding
                      .map((o) => (o.status === "incomplete" ? `${o.department} (incomplete)` : o.department))
                      .join(", ")
                  : "-"}
              </Text>
            </View>
          ))}
        </View>

        {/* Footer on every page */}
        <View style={s.footer} fixed>
          <Text>STI WebC Clearance Portal | {term}</Text>
          <Text render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`} />
        </View>
      </Page>
    </Document>
  );
}

function Meta({ label, value }: { label: string; value: string }) {
  return (
    <View style={s.metaItem}>
      <Text style={s.metaLabel}>{label}</Text>
      <Text style={s.metaValue}>{value}</Text>
    </View>
  );
}

function Kpi({ value, label, last }: { value: string; label: string; last?: boolean }) {
  return (
    <View style={[s.kpi, last ? s.kpiLast : {}]}>
      <Text style={s.kpiValue}>{value}</Text>
      <Text style={s.kpiLabel}>{label}</Text>
    </View>
  );
}

function LegendDot({ color, label }: { color: string; label: string }) {
  return (
    <View style={{ flexDirection: "row", alignItems: "center", marginRight: 14 }}>
      <View style={{ width: 6, height: 6, borderRadius: 3, backgroundColor: color, marginRight: 4 }} />
      <Text style={{ fontSize: 8, color: C.muted }}>{label}</Text>
    </View>
  );
}